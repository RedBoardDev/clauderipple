// macOS attributes a launchd background item to the code signer of the executable it runs.
// Running `node` directly makes System Settings say "Node.js Foundation". So the agent runs a
// tiny app bundle named ClaudeRipple instead: an ad-hoc signed launcher script that execs node
// with the router. Login Items and the background-activity notice then show "ClaudeRipple".

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { findIcon } from "./launcher.ts";

export const BUNDLE_ID = "com.clauderipple.router";

export function bundlePath(home: string): string {
  return path.join(home, "ClaudeRipple.app");
}

export function launcherPath(home: string): string {
  return path.join(bundlePath(home), "Contents", "MacOS", "ClaudeRipple");
}

/** The launcher's text; `repair` compares an existing one against it. */
export function launcherScript(opts: { home: string; node: string; script: string }): string {
  const cli = path.resolve(path.dirname(opts.script), `../../cli/src/index${path.extname(opts.script)}`);
  // Keep the router's exec at column zero: doctor follows that line to check its targets.
  const quote = (value: string) => `"${value.replace(/[\\"$`]/g, "\\$&")}"`;
  return `#!/bin/sh
# ClaudeRipple router launcher (generated by \`clauderipple install\`).
export CLAUDERIPPLE_HOME=${quote(opts.home)}
if [ "\${1:-}" = "tray" ]; then
  exec ${quote(opts.node)} ${quote(cli)} tray --at-login
fi
exec ${quote(opts.node)} ${quote(opts.script)}
`;
}

function writeIfChanged(file: string, content: string | Buffer): boolean {
  const bytes = Buffer.isBuffer(content) ? content : Buffer.from(content);
  try {
    if (fs.readFileSync(file).equals(bytes)) return false;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  fs.writeFileSync(file, bytes);
  return true;
}

function signBundle(app: string): void {
  try {
    execFileSync("codesign", ["--force", "--sign", "-", "--identifier", BUNDLE_ID, app], { stdio: "ignore" });
  } catch (error) {
    console.warn(`ClaudeRipple background bundle could not be signed: ${error}`);
  }
}

export function writeBundle(opts: { home: string; node: string; script: string; version: string }, sign: (app: string) => void = signBundle): string {
  const app = bundlePath(opts.home);
  const contents = path.join(app, "Contents");
  const macos = path.join(contents, "MacOS");
  fs.mkdirSync(macos, { recursive: true });
  const icon = findIcon({ repo: path.resolve(path.dirname(opts.script), "../../..") }, "icon.icns");
  let changed = writeIfChanged(
    path.join(contents, "Info.plist"),
    `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>ClaudeRipple</string>
  <key>CFBundleDisplayName</key><string>ClaudeRipple</string>
  <key>CFBundleIdentifier</key><string>${BUNDLE_ID}</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>ClaudeRipple</string>
${icon ? "  <key>CFBundleIconFile</key><string>icon.icns</string>\n" : ""}  <key>LSUIElement</key><true/>
  <key>LSBackgroundOnly</key><true/>
</dict>
</plist>
`,
  );
  const launcher = launcherPath(opts.home);
  changed = writeIfChanged(launcher, launcherScript(opts)) || changed;
  if ((fs.statSync(launcher).mode & 0o777) !== 0o755) {
    fs.chmodSync(launcher, 0o755);
    changed = true;
  }
  if (icon) {
    fs.mkdirSync(path.join(contents, "Resources"), { recursive: true });
    changed = writeIfChanged(path.join(contents, "Resources", "icon.icns"), fs.readFileSync(icon)) || changed;
  }
  if (changed) sign(app);
  return launcher;
}

export function removeBundle(home: string): void {
  fs.rmSync(bundlePath(home), { recursive: true, force: true });
}
