// Which installation recorded a value in the user's shared Claude settings.
//
// `~/.claude/settings.json` is one file per account and every install on the account writes the
// same keys, so a value is not proof of ownership by itself. Each install records what it actually
// wrote here, beside that file; a value is removed only when this home recorded it and no other
// home records the same value. Anything unrecorded (a hand-written value, or one an older version
// left) is preserved and reported (B02, 2026-10-25).
//
// The store is small JSON beside the settings file: schema 1, one record per home. Its write is
// part of the shared-settings lock in `settings.ts` (`withFileLock`) and lands through
// `writeJsonAtomic` (0600, rename), so two installations cannot lose each other's record and a
// crash never leaves a written value without the record that justifies removing it later.
// A read failure is returned, not thrown, so the caller can say so and leave shared values alone.

import fs from "node:fs";
import path from "node:path";

/** Values this home wrote into settings.json's model slots: slot -> exact value. */
export type SlotClaims = Record<string, string>;

/** Everything one home may have written into the shared client settings. */
export type HomeClaims = {
  slots?: SlotClaims;
  /** Plugin folders this home registered (`CLAUDE_CODE_PLUGIN_DIRS`). */
  mods?: string[];
  /** The exact agent-title hook command this home added. */
  hooks?: string[];
  /** The exact `CLAUDE_CODE_MAX_CONTEXT_TOKENS` this home wrote. */
  contextCap?: string;
  /** Exact per-model autoCompactWindow values generated by this home. */
  compactWindows?: Record<string, number>;
};

export type OwnerStore = { version: 1; homes: Record<string, HomeClaims> };

export function ownersPath(settingsFile: string): string {
  return `${settingsFile}.clauderipple-owners.json`;
}

/** Where an installation's home is recorded: absolute, symlinks resolved when the path exists. */
export function ownerHomeKey(home: string): string {
  const resolved = path.resolve(home);
  try {
    return fs.realpathSync(resolved);
  } catch {
    return resolved;
  }
}

/**
 * A store is accepted whole or not at all. A claim dropped as "malformed" would silently become
 * "nobody recorded this", and the next write would then save over the only evidence — so any
 * unknown version, wrong shape or non-string value makes the whole store an error and the caller
 * writes nothing and deletes nothing (fail closed).
 */
function storeProblem(value: unknown): string | null {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return "not an ownership record";
  const raw = value as { version?: unknown; homes?: unknown };
  if (raw.version !== 1) return `unsupported schema version ${JSON.stringify(raw.version)}`;
  if (raw.homes === null || typeof raw.homes !== "object" || Array.isArray(raw.homes)) return "homes is not an object";
  for (const [home, claims] of Object.entries(raw.homes as Record<string, unknown>)) {
    if (!home) return "a home key is empty";
    if (claims === null || typeof claims !== "object" || Array.isArray(claims)) return `the record for ${home} is not an object`;
    const record = claims as { slots?: unknown; mods?: unknown; hooks?: unknown; contextCap?: unknown; compactWindows?: unknown };
    if (record.compactWindows !== undefined) {
      const windows = record.compactWindows;
      if (!windows || typeof windows !== "object" || Array.isArray(windows) || Object.values(windows).some(v => typeof v !== "number" || !Number.isSafeInteger(v) || v < 100_000 || v > 1_000_000)) return `compactWindows for ${home} is invalid`;
    }
    if (record.contextCap !== undefined && typeof record.contextCap !== "string") return `contextCap for ${home} is not a string`;
    if (record.slots !== undefined) {
      if (record.slots === null || typeof record.slots !== "object" || Array.isArray(record.slots)) return `slots for ${home} is not an object`;
      for (const [slot, model] of Object.entries(record.slots as Record<string, unknown>)) {
        if (typeof model !== "string") return `slots.${slot} for ${home} is not a string`;
      }
    }
    for (const field of ["mods", "hooks"] as const) {
      const list = record[field];
      if (list === undefined) continue;
      if (!Array.isArray(list) || !list.every((entry) => typeof entry === "string")) return `${field} for ${home} is not a list of strings`;
    }
  }
  return null;
}

/**
 * The store beside `settingsFile`. A missing file is an empty store; unreadable, malformed or
 * unsupported content is an error with an empty store, and the original file is never rewritten by
 * this function. Callers must treat the error as "ownership unknown" (no deletion, no writes).
 */
export function readOwners(settingsFile: string): { store: OwnerStore; error: string | null } {
  const file = ownersPath(settingsFile);
  let text: string;
  try {
    text = fs.readFileSync(file, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return { store: { version: 1, homes: {} }, error: null };
    return { store: { version: 1, homes: {} }, error: `${file}: ${(error as Error).message}` };
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch (error) {
    return { store: { version: 1, homes: {} }, error: `${file}: ${(error as Error).message}` };
  }
  const problem = storeProblem(parsed);
  if (problem) return { store: { version: 1, homes: {} }, error: `${file}: ${problem}; it was left untouched` };
  return { store: parsed as OwnerStore, error: null };
}

export function claimsOf(store: OwnerStore, home: string): HomeClaims {
  return store.homes[ownerHomeKey(home)] ?? {};
}

/** Records this home's claims; an empty record is dropped, and so is the store when no home has any. */
export function setClaims(store: OwnerStore, home: string, claims: HomeClaims): void {
  const key = ownerHomeKey(home);
  const next: HomeClaims = {};
  if (claims.slots && Object.keys(claims.slots).length) next.slots = claims.slots;
  if (claims.mods?.length) next.mods = claims.mods;
  if (claims.hooks?.length) next.hooks = claims.hooks;
  if (claims.contextCap) next.contextCap = claims.contextCap;
  if (claims.compactWindows && Object.keys(claims.compactWindows).length) next.compactWindows = claims.compactWindows;
  if (next.slots || next.mods || next.hooks || next.contextCap || next.compactWindows) store.homes[key] = next;
  else delete store.homes[key];
}

/** True when another installation records this exact value: never ours to delete, whatever we wrote. */
export function claimedElsewhere(store: OwnerStore, home: string, pick: (claims: HomeClaims) => string | string[] | undefined, value: string): boolean {
  const key = ownerHomeKey(home);
  for (const [other, claims] of Object.entries(store.homes)) {
    if (other === key) continue;
    const claimed = pick(claims);
    if (Array.isArray(claimed) ? claimed.includes(value) : claimed === value) return true;
  }
  return false;
}
